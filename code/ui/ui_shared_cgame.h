/*
 * The cgame's own copy of ui_shared.c in the static build (issue #459).
 *
 * Retail 1.32c built ui_shared.c into both Team Arena QVMs, cgame (with
 * -DCGAME) and ui, so each module had its own menus, string pool, memory
 * pool, display context and keyword hashes. This build links both modules
 * into one application, so the cgame compiles ui_shared.c into its own
 * archive and every global ui_shared.c defines gets a CGUI_ name in the
 * cgame. ui_shared.h includes this header first, so ui_shared.c and every
 * cgame file that uses it see the same names; the ui keeps the plain ones.
 * The cgame copy calls the cgame's traps (q_static_linked.h) and draws
 * through the cgame's display context, as retail's did.
 *
 * CG_ would collide with the cgame's own CG_AdjustFrom640. When ui_shared.c
 * gains a global, add it here: the Mac link fails (cmake/static_modules.py)
 * and tests/run_static_module_reset_tests.sh fails while one is missing.
 */
